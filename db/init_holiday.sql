-- 공휴일(휴무일) 캘린더 -- loan-code-service가 소유, loan-schedule-service가
-- 영업일(+1영업일 등) 판단 시 조회해서 쓴다 (BusinessDayCalendar 참고).
--
-- 관공서의 공휴일에 관한 규정 기준: 신정/현충일은 대체공휴일 적용 대상이 아니고,
-- 설날·추석 연휴는 그 3일 구간에 "일요일"이 포함될 때만 대체공휴일이 발생하며,
-- 어린이날/3·1절/광복절/개천절/한글날/부처님오신날/성탄절(+2026년부터 재지정된
-- 제헌절)은 토요일 또는 일요일에 해당하면 대체공휴일이 발생한다(다음 첫 평일).
-- 근로자의날(5/1)은 별도 법령(근로자의 날 제정에 관한 법률) 소관이라 이번 시드에는
-- 넣지 않았다 -- 실무상 은행도 쉬는 날이라 필요해지면 추가해야 한다.
--
-- 2026~2027년은 확정된 관공서 공휴일 자료 기준. 2028년은 설날/추석 등 음력 날짜까지
-- 이미 계산되어 공개된 값이라 함께 적재했다(요청대로 "28년까지 정해진" 것만).

CREATE TABLE holiday (
    holiday_dt   DATE PRIMARY KEY,
    holiday_name VARCHAR(100) NOT NULL
);

COMMENT ON TABLE holiday IS '은행 영업일 판단용 휴무일 캘린더 (관공서 공휴일 + 대체공휴일). 근로자의날 미포함.';
COMMENT ON COLUMN holiday.holiday_dt IS '휴무일자';
COMMENT ON COLUMN holiday.holiday_name IS '휴무일 명칭';

